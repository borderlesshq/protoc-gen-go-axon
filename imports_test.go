package main

import (
	"strings"
	"testing"
)

func TestPruneImports(t *testing.T) {
	src := `// Code generated by protoc-gen-go-axon. DO NOT EDIT.

package accounts

import (
	"context"
	"io"
	"strings"

	"github.com/nats-io/nats.go"
	"go.opentelemetry.io/otel/codes"
	pb "google.golang.org/protobuf/proto"
	_ "embed"
)

// Keep this comment.
func Call(ctx context.Context, nc *nats.Conn) error {
	_ = pb.Marshal
	return nil
}
`
	out, err := pruneImports([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	got := string(out)

	for _, keep := range []string{`"context"`, `"github.com/nats-io/nats.go"`, `pb "google.golang.org/protobuf/proto"`, `_ "embed"`, "// Keep this comment."} {
		if !strings.Contains(got, keep) {
			t.Errorf("missing %s in:\n%s", keep, got)
		}
	}
	for _, drop := range []string{`"io"`, `"strings"`, `"go.opentelemetry.io/otel/codes"`} {
		if strings.Contains(got, drop) {
			t.Errorf("unused import %s kept in:\n%s", drop, got)
		}
	}
}

func TestPruneImportsSingleAndNone(t *testing.T) {
	one := "package p\n\nimport (\n\t\"fmt\"\n\t\"io\"\n)\n\nvar _ = fmt.Sprint\n"
	out, err := pruneImports([]byte(one))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), `"io"`) || !strings.Contains(string(out), `"fmt"`) {
		t.Errorf("single import case:\n%s", out)
	}

	none := "package p\n\nimport (\n\t\"io\"\n)\n\nvar X = 1\n"
	out, err = pruneImports([]byte(none))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), "import") {
		t.Errorf("empty import block left:\n%s", out)
	}
}

func TestAssumedPackageName(t *testing.T) {
	for path, want := range map[string]string{
		"github.com/nats-io/nats.go":       "nats",
		"go.opentelemetry.io/otel/trace":   "trace",
		"gopkg.in/yaml.v3":                 "yaml",
		"github.com/foo/go-bar":            "bar",
		"github.com/jackc/pgx/v5":          "pgx",
		"google.golang.org/protobuf/proto": "proto",
		"encoding/json":                    "json",
	} {
		if got := assumedPackageName(path); got != want {
			t.Errorf("%s: got %q want %q", path, got, want)
		}
	}
}
