// TemplateData holds all data needed for template execution
type TemplateData struct {
	PackageName string
	SourceFile  string
	Services    []*ServiceData
}

// ServiceData holds data for a single service
type ServiceData struct {
	Name        string
	Methods     []*MethodData
	ServiceName string
}

// MethodData holds data for a single method
type MethodData struct {
	Name              string
	ServiceName       string
	InputType         string
	OutputType        string
	InputTypeName     string
	OutputTypeName    string
	IsClientStreaming bool
	IsServerStreaming bool
	Topic             string
}

// Template helper functions
var templateFuncs = template.FuncMap{
	"lower": strings.ToLower,
	"title": strings.Title,
	"clientType": func(serviceName string) string {
		return strings.ToLower(serviceName[:1]) + serviceName[1:] + "Client"
	},
	"streamType": func(serviceName, methodName, side string) string {
		return serviceName + "_" + methodName + side
	},
	"streamImplType": func(serviceName, methodName, side string) string {
		streamType := serviceName + "_" + methodName + side
		return strings.ToLower(streamType[:1]) + streamType[1:]
	},
	"isUnary": func(m *MethodData) bool {
		return !m.IsClientStreaming && !m.IsServerStreaming
	},
	"isServerStreaming": func(m *MethodData) bool {
		return !m.IsClientStreaming && m.IsServerStreaming
	},
	"isClientStreaming": func(m *MethodData) bool {
		return m.IsClientStreaming && !m.IsServerStreaming
	},
	"isBidirectional": func(m *MethodData) bool {
		return m.IsClientStreaming && m.IsServerStreaming
	},
	// Helper functions to check if service has specific streaming types
	"hasServerStreaming": func(methods []*MethodData) bool {
		for _, m := range methods {
			if !m.IsClientStreaming && m.IsServerStreaming {
				return true
			}
		}
		return false
	},
	"hasClientStreaming": func(methods []*MethodData) bool {
		for _, m := range methods {
			if m.IsClientStreaming && !m.IsServerStreaming {
				return true
			}
		}
		return false
	},
	"hasBidirectional": func(methods []*MethodData) bool {
		for _, m := range methods {
			if m.IsClientStreaming && m.IsServerStreaming {
				return true
			}
		}
		return false
	},
	// Helper to check if service has client streaming OR bidirectional (for shared types)
	"hasClientOrBidiStreaming": func(methods []*MethodData) bool {
		for _, m := range methods {
			if m.IsClientStreaming {
				return true
			}
		}
		return false
	},
}

